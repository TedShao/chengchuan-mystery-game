// Morning conversation reads delivered facts. It cannot book, grant records or change ownership.
export function morningReply(s,who,raw){
 const t=String(raw).replace(/(?:不是说|不是问|不问|不谈)[^，。；!?！？]*(?:[，。；!?！？]|$)/g,'').replace(/^.*(?:我只问|我问的是)/,'').trim();
 const knows=id=>s.known[who]?.includes(id),c=s.continuity||{};
 const timing=/几点|什么安排|联系.*(?:暂缓|改成)|现在.*(?:约|联系)|收到.*通知|通知.*收到|知道.*联系/.test(t);
 const ownership=/不接手|不接窗口|没接窗口|不参与|谁负责|谁经办|还是我|我接客户/.test(t);
 const intent=/只.*(?:答应|了解|听听)|是不是.*(?:了解|同意|注册)|愿意.*(?:了解|注册)|打算/.test(t);
 const provenance=/核验|核过|核实|扫描件|已收|已测试|主体资料|真实经营|准入|原始来源/.test(t);
 const business=/为啥|为什么|干吗|还要.*看|公司.*(?:同一个|同一家)|罗青.*(?:同一个|同一家)|同一个.*(?:公司|项目)|介绍.*(?:她|罗青)/.test(t);
 if(/刚.*(?:私下|私信)|私下.*(?:沈念|问)|她怎么回|她.*回复.*(?:知道|收到)/.test(t)&&who!=='shen')return knows('verify')?'我收到过核验事项，但没有收到你和沈念后来那封私人回复。要我核对，请转交具体原往来。':'你说你另外问了沈念，这封私人往来没有发给我。我不知道她回了什么；你可以明确转交原回复，我只核对收到的内容。';
 if(/谁.*付|公司.*(?:赚|收入)|免费.*课|课程.*免费|委托费|运营费/.test(t)&&!/两万|个人转款/.test(t))return who==='tang'?'课程对用户免费，基础运营费和持续协作服务费由知禾在线服务有限公司按委托支付。附件里的“境外项目服务”是项目归档，不是用户个人转款的到账证明。你要核对具体范围，可以查我给的费用附件。':'本组课程与介绍、转交服务由知禾项目委托，服务费范围由唐婧核对。她有本公司的委托附件；个人转款另有记录，不能合成一笔。';
 if(provenance){
  if(who==='zhou'&&/找谁|问谁|谁.*(?:提供|提交)|扫描件.*(?:后来|来源)/.test(t))return knows('verify')?'这项已向沈念发出来源询问，还没收到新的依据。你如果另外问过她，把她的原回复转我，我再核对。':'扫描件是沈念交来的，原始材料由她向业务端索取。我这里还没有后续独立核验记录；要追这份材料从哪里来，先问她。';
  if(who==='zhou')return knows('verify')?'资料来源询问已经转给沈念，原业务端材料仍在，新的独立核验依据还没有补到。我不能把“已收”改说成已经实地核过。':'我当时确认的是国内服务清单、入口和联系人能否接上。扫描件是沈念提交的；这份准入记录没有记载实地经营核查。你想核哪项来源，可以写给资料提交方，不能只凭“已收”替它补一项核验。';
  if(who==='tang')return '主体资料的项目准入由周衡审核，我核的是服务委托与本组费用。我的附件不能替他证明那家公司实际如何经营；查审核依据要问他。';
  if(who==='shen')return knows('verify')?'你的来源询问我收到了，已经向资料提供方问。现有服务介绍来自业务端，来源依据还没补到，不能拿同一份介绍当成新的证明。':'主体及入口资料是业务端提供的，我负责向国内交材料。你要追原始来源，请列出具体那一项；我不能用“发过资料”代替核验结果。';
  return knows('admission')?'你发来的准入原件我收到了，但这不是我审核的。上面的核对范围要问周衡，我只经办介绍和转交。':'准入资料不是我审核的，我也没有收到你提到的那份原件。介绍记录我能核，审核与资料来源请问周衡。';
 }
 if(business){
  if(/同一个|同一家/.test(t))return who==='xiaoyu'?'两次介绍都是知禾项目的沈念接的，我保留的介绍记录可以对照。但同一个联系人不等于我已经核过主体公司的实际经营；许川这次问的是公司名称和今天联系的内容。':'委托名称是知禾在线服务有限公司。两次具体怎样介绍由小雨经办，名称相同不替代实际服务与主体资料的核对。';
  if(who==='xiaoyu')return (c.windowDecision==='declined'?'你拒绝的是下周窗口安排，我没有把这次核对算成你接手。':'今天仍由我经办，核对回复不等于接手窗口。')+'昨天罗青的材料改了，今天许川还在问后续跟谁联系。我把待发回复留给你看，是想核对准备怎么介绍；没空我会自己问清楚，不能让用户等着。';
  if(who==='zhou')return '收窄罗青案例只改了那份表述，公司的介绍与转交服务仍在继续。你不承担窗口，也可以核对自己经手的记录。许川这条由小雨处理；要问公司凭什么开展这些服务，可以查委托范围和当时的项目准入。';
 }
 if(timing){
  const k=s.bookingKnown?.[who];
  if(who==='tang'&&!k)return '你提到了联系调整，但我没有收到预约变更通知。我不经办许川的联系，不能替小雨确认现在的时间。';
  if(who==='tang')return k.appointment==='general_confirmed'?'你转来的原确认写的是15:10普通介绍。我只收到这一封，之后有无变更要问小雨。':'你转来的原回复同意先等文字说明。我不经办预约，后续是否另约要看新的确认。';
  if(!k)return '我没有收到这次预约的具体确认或变更。可以先把相关原往来发来，当前时间请以小雨收到的用户确认记录为准。';
  if(who==='zhou')return k.appointment==='paused'?'我最后确认的是暂缓联系，并通知了小雨。后来有没有重新约，我没有收到新的确认；不能把那次审批当成现在的完整安排。':k.appointment==='general_confirmed'?'我收到你转来的15:10普通介绍往来。仅按这封确认时间，没有据此核实业务本身。':'我收到的是当时的候选时段，还没有用户最终确认。';
  return k.appointment==='general_confirmed'?'目前许川已确认15:10普通介绍，不做账号内演示。小雨继续经办，改时间没有替你接手客户。':k.appointment==='paused'?'目前先等文字说明，原时段已释放。重新联系需要再问许川，不能直接恢复旧预约。':'原14:30只是暂留。许川说有空了解，但还没确认页面上的账号准备。';
 }
 if(/看过.*(?:回复|稿)|收到.*(?:那封|待发)|(?:回复|稿).*看过/.test(t)&&who!=='xiaoyu')return '那封待发稿没有发给我。我不能评价没收到的正文；可以转交具体内容，或先问经办人小雨。';
 if(ownership||intent){
  if(who!=='xiaoyu')return who==='tang'?'我不负责许川联系。你是否参与核对和谁经办是两回事，请向小雨确认。':'许川由小雨经办。核对一封回复不会替你接手客户，下周窗口安排也要单独答复。';
  const role=s.participation==='declined'?'你已退出这次核对，我继续处理。':c.windowDecision==='declined'?'下周窗口你已经拒绝；这次仍由我经办，你可以只核一句或不参与。':'这次仍由我经办，不会因为你提了意见就算接手。';
  return role+(intent?s.wishKnown?'他后来明确说今天不注册，只想了解。现在要按实际联系记录处理，不再把空闲时间当作账号演示的同意。':'他目前只说有时间先了解；是否愿意按页面做准备还没确认。我会问清楚，不能替他补成同意。':'你对联系形式改口，改变的是本次建议，不是客户负责人的名字。');
 }
 return null;
}
